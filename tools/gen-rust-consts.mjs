// TS 版から Rust 版の定数 (rust/src/consts.rs) を書き出す
import { _internal as I } from "../dist/bls.js";
import fs from "fs";
const { P, R, G1, G2 } = I;
const C = I.consts;
const hx = (n) => `"${n.toString(16).padStart(96, "0")}"`;
const fp = (n) => `fp(${hx(n)})`;
const fp2 = (a) => `Fp2::new(${fp(a[0])}, ${fp(a[1])})`;
const lines = [];
const out = (s) => lines.push(s);
out("// 自動生成: tools/gen-rust-consts.mjs (TS 版から書き出し)。手で編集しない");
out("use crate::fp::{fp, limbs, Fp};");
out("use crate::fp2::Fp2;\n");
out(`pub const P_LIMBS: [u32; 12] = limbs(${hx(P)});`);
out(`pub const R_ORDER: [u32; 12] = limbs(${hx(R)});`);
out(`pub const EXP_P_MINUS_2: [u32; 12] = limbs(${hx(P - 2n)});`);
out(`pub const EXP_SQRT: [u32; 12] = limbs(${hx((P + 1n) / 4n)});`);
out(`pub const EXP_INV_SQRT: [u32; 12] = limbs(${hx((P - 3n) / 4n)});`);
out(`pub const EXP_LEGENDRE: [u32; 12] = limbs(${hx((P - 1n) / 2n)});`);
out(`pub const HALF_P: [u32; 12] = limbs(${hx((P - 1n) / 2n)});`);
out(`pub const X_ABS: u64 = 0x${C.X_ABS.toString(16)};`);
out(`pub const INV2: Fp = ${fp(C.INV2)};`);
out(`pub const BETA: Fp = ${fp(C.BETA)};`);
out(`pub const G1_X: Fp = ${fp(G1[0])};`);
out(`pub const G1_Y: Fp = ${fp(G1[1])};`);
out(`pub const G2_X: Fp2 = ${fp2(G2[0])};`);
out(`pub const G2_Y: Fp2 = ${fp2(G2[1])};`);
out(`pub const PSI_X: Fp2 = ${fp2(C.PSI_X)};`);
out(`pub const PSI_Y: Fp2 = ${fp2(C.PSI_Y)};`);
out(`pub const FROB: [[Fp2; 6]; 3] = [${C.FROB.map((row) => `[${row.map(fp2).join(", ")}]`).join(",\n  ")}];`);
out(`pub const SSWU_A: Fp2 = ${fp2(C.SSWU_A.map((x) => ((x % P) + P) % P))};`);
out(`pub const SSWU_B: Fp2 = ${fp2(C.SSWU_B)};`);
out(`pub const SSWU_Z: Fp2 = ${fp2(C.SSWU_Z)};`);
out(`pub const SSWU_MB_A: Fp2 = ${fp2(C.SSWU_MB_A)};`);
out(`pub const SSWU_B_ZA: Fp2 = ${fp2(C.SSWU_B_ZA)};`);
const iso = (k) => `[${k.map(fp2).join(", ")}]`;
out(`pub const ISO_XNUM: [Fp2; 4] = ${iso(C.ISO[0])};`);
out(`pub const ISO_XDEN: [Fp2; 3] = ${iso(C.ISO[1])};`);
out(`pub const ISO_YNUM: [Fp2; 4] = ${iso(C.ISO[2])};`);
out(`pub const ISO_YDEN: [Fp2; 4] = ${iso(C.ISO[3])};`);
fs.writeFileSync(new URL("../rust/src/consts.rs", import.meta.url), lines.join("\n") + "\n");
console.log("rust/src/consts.rs:", lines.length, "行");
